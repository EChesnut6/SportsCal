function getConference(team, league) {
  const id = String(team.id || '');

  if (league === 'ncaab') {
    if (CBB_TEAM_CONF_BY_ID[id]) {
      return CBB_TEAM_CONF_BY_ID[id];
    }
    return 'Independent';
  }

  if (CFB_TEAM_CONF_BY_ID[id]) {
    return CFB_TEAM_CONF_BY_ID[id];
  }

  return 'FCS';
}

function processTeams(teams, league) {
  const seen = new Set();
  const list = [];

  teams.forEach(t => {
    if (!t.id || seen.has(t.id)) return;
    seen.add(t.id);

    const fullId = `${league}-${t.id}`;
    const conf = getConference(t, league);

    list.push({
      id: fullId,
      displayName: t.displayName || t.name,
      shortDisplayName: t.shortDisplayName || t.location || t.displayName,
      abbreviation: t.abbreviation || t.displayName?.substring(0, 3).toUpperCase(),
      color: t.color || '1e293b',
      alternateColor: t.alternateColor,
      logo: t.logo || t.logos?.[0]?.href || `https://a.espncdn.com/i/teamlogos/ncaa/500/${t.id}.png`,
      league: league,
      conference: conf
    });
  });

  return list.sort((a, b) => a.displayName.localeCompare(b.displayName));
}

async function run() {
  const cfbRaw = JSON.parse(fs.readFileSync('testing/espn_cfb_teams.json', 'utf-8'));
  const cbbRaw = JSON.parse(fs.readFileSync('testing/espn_cbb_teams.json', 'utf-8'));

  const cfbProcessed = processTeams(cfbRaw, 'ncaaf');
  const cbbProcessed = processTeams(cbbRaw, 'ncaab');

  console.log(`Processed ${cfbProcessed.length} NCAAF teams and ${cbbProcessed.length} NCAAB teams.`);

  fs.writeFileSync('testing/cfb_processed.json', JSON.stringify(cfbProcessed, null, 2));
  fs.writeFileSync('testing/cbb_processed.json', JSON.stringify(cbbProcessed, null, 2));
}

